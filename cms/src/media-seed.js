'use strict';

// ─────────────────────────────────────────────────────────────────────────────
// Media seeding — uploads every bundled image into the Media Library and links
// each media field to it, so the client sees real images in the CMS before the
// first deploy (and a fresh deploy fills them in automatically).
//
// Idempotent:
//  - an image is uploaded only once (matched by file name in the Media Library)
//  - a media field is filled only when it is currently empty AND its seed
//    image was uploaded in THIS run — the first boot (or a deploy that ships
//    new bundled images) fills everything, while later restarts never
//    resurrect images an editor removed on purpose and never touch drafts
//
// Source images + manifest come from cms/data/seed-media/ (generated by
// `npm run cms:seed-dump`). The manifest maps AssetKey → filename; the seed.json
// content still carries the AssetKey strings in every media field, which we
// resolve to the uploaded file id here.
// ─────────────────────────────────────────────────────────────────────────────

const fs = require('fs');
const path = require('path');

const MIME = {
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png',
  '.webp': 'image/webp', '.svg': 'image/svg+xml', '.gif': 'image/gif', '.avif': 'image/avif',
};

/** Populate object following every media + component attribute recursively. */
function buildPopulate(strapi, uid, depth = 0) {
  if (depth > 8) return true;
  const model = strapi.getModel(uid);
  if (!model) return true;
  const populate = {};
  for (const [name, attr] of Object.entries(model.attributes)) {
    if (attr.type === 'media') populate[name] = true;
    else if (attr.type === 'component') {
      const sub = buildPopulate(strapi, attr.component, depth + 1);
      populate[name] = sub === true ? true : { populate: sub };
    }
  }
  return Object.keys(populate).length > 0 ? populate : true;
}

/**
 * Upload every image listed in the manifest that is not in the Media Library
 * yet. Returns { [AssetKey]: fileId } for files uploaded in THIS run only —
 * fields are backfilled solely from fresh uploads (see header).
 */
async function ensureUploads(strapi, mediaDir, manifest) {
  const uploadService = strapi.plugin('upload').service('upload');
  const map = {};
  for (const [key, filename] of Object.entries(manifest)) {
    try {
      const existing = await strapi.db.query('plugin::upload.file').findOne({ where: { name: filename } });
      if (existing) continue;

      const filePath = path.join(mediaDir, filename);
      if (!fs.existsSync(filePath)) { strapi.log.warn(`[media-seed] missing file ${filename}`); continue; }
      const ext = path.extname(filename).toLowerCase();
      const [file] = await uploadService.upload({
        // fileInfo.name sets the Media Library display name (otherwise "unamed").
        data: { fileInfo: { name: filename, alternativeText: '', caption: '' } },
        files: {
          // formidable v3 convention (lowercase "name"), used by Strapi v5.
          filepath: filePath,
          originalFilename: filename,
          mimetype: MIME[ext] || 'application/octet-stream',
          size: fs.statSync(filePath).size,
        },
      });
      map[key] = file.id;
      strapi.log.info(`[media-seed] uploaded ${filename}`);
    } catch (err) {
      strapi.log.warn(`[media-seed] upload failed for ${filename}: ${err.message}`);
    }
  }
  return map;
}

/**
 * Convert a populated entry/component into a document-service update input:
 *  - media (single) → file id ; media (multiple) → [file ids]
 *  - components recurse (ids dropped: Strapi recreates them with the same data,
 *    which sidesteps draft/publish component-id mismatches)
 *  - relations are skipped (never touch createdBy/updatedBy)
 */
function toInput(strapi, uid, value) {
  const model = strapi.getModel(uid);
  if (!model || value == null) return value;
  const out = {};
  for (const [name, attr] of Object.entries(model.attributes)) {
    const v = value[name];
    if (v == null) continue;
    switch (attr.type) {
      case 'media':
        out[name] = attr.multiple ? (Array.isArray(v) ? v.map((f) => f.id).filter(Boolean) : []) : (v.id ?? null);
        break;
      case 'component':
        out[name] = attr.repeatable
          ? (Array.isArray(v) ? v.map((item) => toInput(strapi, attr.component, item)) : [])
          : toInput(strapi, attr.component, v);
        break;
      case 'relation':
        break;
      default:
        out[name] = v;
    }
  }
  return out;
}

/**
 * Fill empty media fields on an update input from the seed's AssetKeys,
 * resolved to uploaded file ids. Returns true if anything was filled.
 */
function fillMedia(strapi, uid, input, seed, uploadMap) {
  if (!seed || typeof seed !== 'object' || !input) return false;
  const model = strapi.getModel(uid);
  if (!model) return false;
  let changed = false;
  for (const [name, attr] of Object.entries(model.attributes)) {
    const seedVal = seed[name];
    if (seedVal == null) continue;
    if (attr.type === 'media') {
      if (attr.multiple) {
        const empty = !Array.isArray(input[name]) || input[name].length === 0;
        if (empty && Array.isArray(seedVal)) {
          const ids = seedVal.map((k) => uploadMap[k]).filter(Boolean);
          if (ids.length) { input[name] = ids; changed = true; }
        }
      } else if (input[name] == null && typeof seedVal === 'string') {
        const id = uploadMap[seedVal];
        if (id) { input[name] = id; changed = true; }
      }
    } else if (attr.type === 'component') {
      if (attr.repeatable && Array.isArray(input[name]) && Array.isArray(seedVal)) {
        input[name].forEach((item, i) => {
          if (fillMedia(strapi, attr.component, item, seedVal[i], uploadMap)) changed = true;
        });
      } else if (!attr.repeatable && input[name] && typeof seedVal === 'object') {
        if (fillMedia(strapi, attr.component, input[name], seedVal, uploadMap)) changed = true;
      }
    }
  }
  return changed;
}

async function backfillEntry(strapi, uid, entry, seedRow, uploadMap) {
  const input = toInput(strapi, uid, entry);
  if (!fillMedia(strapi, uid, input, seedRow, uploadMap)) return false;
  await strapi.documents(uid).update({ documentId: entry.documentId, data: input });
  // Re-publish so the filled images are live (update targets the draft).
  try { await strapi.documents(uid).publish({ documentId: entry.documentId }); } catch { /* no D&P */ }
  return true;
}

/**
 * Upload all bundled images and link every empty media field to them.
 * @param singleUids  { seedName: uid }
 * @param collectionUids { seedName: uid }
 */
async function seedMedia(strapi, seed, { singleUids, collectionUids }) {
  const mediaDir = path.join(process.cwd(), 'data', 'seed-media');
  const manifestPath = path.join(mediaDir, 'manifest.json');
  if (!fs.existsSync(manifestPath)) {
    strapi.log.info('[media-seed] no seed-media/manifest.json — skipping image upload');
    return;
  }
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const uploadMap = await ensureUploads(strapi, mediaDir, manifest);
  if (Object.keys(uploadMap).length === 0) {
    strapi.log.info('[media-seed] no new bundled images — nothing to link');
    return;
  }

  // Types without any media/component attribute return `true` from
  // buildPopulate; document service rejects `populate: true`, so pass undefined.
  const popOf = (uid) => {
    const p = buildPopulate(strapi, uid);
    return p === true ? undefined : p;
  };

  let filled = 0;
  for (const [name, uid] of Object.entries(singleUids)) {
    if (!seed[name]) continue;
    try {
      const entry = await strapi.documents(uid).findFirst({ populate: popOf(uid), status: 'published' });
      if (entry && (await backfillEntry(strapi, uid, entry, seed[name], uploadMap))) filled++;
    } catch (err) {
      strapi.log.warn(`[media-seed] ${name}: ${err.message}`);
    }
  }
  for (const [name, uid] of Object.entries(collectionUids)) {
    const rows = seed[name];
    if (!Array.isArray(rows)) continue;
    try {
      const entries = await strapi.documents(uid).findMany({ populate: popOf(uid), sort: 'order:asc', status: 'published', limit: 200 });
      for (let i = 0; i < entries.length; i++) {
        if (await backfillEntry(strapi, uid, entries[i], rows[i], uploadMap)) filled++;
      }
    } catch (err) {
      strapi.log.warn(`[media-seed] ${name}: ${err.message}`);
    }
  }
  if (filled > 0) strapi.log.info(`[media-seed] linked images into ${filled} entr${filled === 1 ? 'y' : 'ies'}`);
  else strapi.log.info('[media-seed] all media fields already set — nothing to do');
}

module.exports = { seedMedia };
